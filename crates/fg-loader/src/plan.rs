//! Serializable loader install plans.
//!
//! A plan is produced while the wizard is still open and then stored inside
//! `fg-game`'s `InstallPlan`. It contains everything the loader node needs after
//! the vanilla download finishes: the child `version.json`, extra library
//! downloads, and ordered post-download steps (zip copies, Forge processors,
//! OptiFine patching). No network access happens while executing it.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};

use crate::kind::LoaderKind;

/// Bump when the on-disk shape changes incompatibly.
pub const LOADER_PLAN_SCHEMA_VERSION: u32 = 1;

/// One file the loader install must materialize.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LoaderFile {
    pub purpose: LoaderFilePurpose,
    /// Relative to the launcher data root.
    pub path: PathBuf,
    /// Official URL; mirror rules are applied by the caller.
    pub url: String,
    #[serde(default)]
    pub sha1: Option<String>,
    #[serde(default)]
    pub size: Option<u64>,
}

/// Why a loader file is needed; drives CLI summaries.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum LoaderFilePurpose {
    Installer,
    Library,
    Mappings,
    Data,
}

impl LoaderFilePurpose {
    #[must_use]
    pub const fn label(self) -> &'static str {
        match self {
            Self::Installer => "installer",
            Self::Library => "libraries",
            Self::Mappings => "mappings",
            Self::Data => "install data",
        }
    }
}

/// One entry copied out of a zip archive.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ZipCopy {
    pub entry: String,
    /// Relative to the launcher data root.
    pub target: PathBuf,
}

/// A generated artifact whose SHA-1 is checked after a processor ran.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OutputCheck {
    /// Relative to the launcher data root.
    pub path: PathBuf,
    pub sha1: String,
}

/// Post-download work, executed in order by [`crate::execute`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "step", rename_all = "camelCase")]
pub enum InstallStep {
    /// Copy selected entries from an archive (relative path).
    Extract {
        archive: PathBuf,
        entries: Vec<ZipCopy>,
    },
    /// Copy every entry under a zip prefix into a destination directory.
    ExtractPrefix {
        archive: PathBuf,
        prefix: String,
        destination: PathBuf,
    },
    /// Run one Forge/NeoForge processor.
    RunProcessor {
        label: String,
        /// Jar path relative to the data root; its manifest names the main class.
        jar: PathBuf,
        classpath: Vec<PathBuf>,
        args: Vec<String>,
        #[serde(default)]
        outputs: Vec<OutputCheck>,
    },
    /// Run OptiFine's patcher against the vanilla client jar.
    PatchOptiFine {
        input: PathBuf,
        installer: PathBuf,
        patcher_class: String,
        output: PathBuf,
    },
    /// Copy a file inside the data root (used by old OptiFine installers).
    CopyFile { source: PathBuf, target: PathBuf },
}

impl InstallStep {
    /// Short label for errors and progress messages.
    #[must_use]
    pub fn label(&self) -> &str {
        match self {
            Self::Extract { .. } => "extract",
            Self::ExtractPrefix { .. } => "extract maven",
            Self::RunProcessor { label, .. } => label,
            Self::PatchOptiFine { .. } => "optifine patcher",
            Self::CopyFile { .. } => "copy",
        }
    }
}

/// Everything needed to install a loader for one Minecraft version.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LoaderPlan {
    pub schema_version: u32,
    pub kind: LoaderKind,
    pub loader_version: String,
    /// Concrete id under `shared/versions/<id>`.
    pub version_id: String,
    pub base_id: String,
    pub main_class: String,
    pub java_major: u32,
    /// Raw child `version.json` content written during finalize.
    pub version_json: String,
    pub files: Vec<LoaderFile>,
    pub steps: Vec<InstallStep>,
}

impl LoaderPlan {
    /// Total known download size, used for progress weights.
    #[must_use]
    pub fn total_bytes(&self) -> u64 {
        self.files.iter().filter_map(|file| file.size).sum()
    }

    /// Removes a planned file (e.g. a coordinate superseded by a mapping
    /// download generated by the launcher).
    pub fn remove_file(&mut self, path: &std::path::Path) {
        self.files.retain(|file| file.path != path);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn plans_round_trip_through_json() {
        let plan = LoaderPlan {
            schema_version: LOADER_PLAN_SCHEMA_VERSION,
            kind: LoaderKind::Forge,
            loader_version: "47.4.29".into(),
            version_id: "1.20.1-forge-47.4.29".into(),
            base_id: "1.20.1".into(),
            main_class: "cpw.mods.bootstraplauncher.BootstrapLauncher".into(),
            java_major: 17,
            version_json: "{\"id\":\"1.20.1-forge-47.4.29\"}".into(),
            files: vec![LoaderFile {
                purpose: LoaderFilePurpose::Installer,
                path: PathBuf::from("cache/loaders/forge/installer.jar"),
                url: "https://example.invalid/installer.jar".into(),
                sha1: None,
                size: Some(4),
            }],
            steps: vec![InstallStep::RunProcessor {
                label: "jarsplitter".into(),
                jar: PathBuf::from("shared/libraries/jarsplitter.jar"),
                classpath: vec![PathBuf::from("shared/libraries/asm.jar")],
                args: vec!["--input".into(), "client.jar".into()],
                outputs: vec![OutputCheck {
                    path: PathBuf::from("shared/libraries/client-slim.jar"),
                    sha1: "abc".into(),
                }],
            }],
        };
        let text = serde_json::to_string(&plan).expect("serialize");
        let decoded: LoaderPlan = serde_json::from_str(&text).expect("deserialize");
        assert_eq!(decoded, plan);
        assert_eq!(decoded.total_bytes(), 4);
        assert_eq!(decoded.steps[0].label(), "jarsplitter");
    }
}
